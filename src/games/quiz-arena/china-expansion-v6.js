function questionsFromRows(prefix, category, rows, prompt, explain) {
  return rows.map((row, index) => {
    const answer = row[1], distractors = [];
    for (let offset = 1; distractors.length < 3; offset += 1) {
      const candidate = rows[(index + offset * 7) % rows.length][1];
      if (candidate !== answer && !distractors.includes(candidate)) distractors.push(candidate);
    }
    return choice(`${prefix}-${String(index + 1).padStart(3, "0")}`, category, prompt(row), answer, distractors, explain(row));
  });
}

