function chinaFirstQuestion(question) {
  if (!question) return false;
  if (question.chinaFeatured || question.worldFamous) return true;
  const text = `${question.prompt || ""} ${question.answer || ""} ${question.explanation || ""}`;
  if (CHINA_MARKERS.test(text) || WORLD_ICONS.test(text)) return true;
  if (["科学与科技", "自然动物", "趣味冷知识", "生活常识", "美食"].includes(question.category)) {
    return UNIVERSAL_TOPICS.test(text) && !FOREIGN_CONTEXT.test(text);
  }
  return false;
}

